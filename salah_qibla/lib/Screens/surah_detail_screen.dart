import 'package:flutter/material.dart';

import '../services/quran_api_service.dart';
import 'surah_audio_bar.dart';

/// SurahDetailScreen
///
/// 8 مکمل سورتیں — عربی متن + اردو ترجمہ (فتح محمد جالندھری)
/// کل آیات: 195  (کوئی آیت مِسنگ نہیں)
///
///   1. Al-Fatihah  ..... 7  آیات
///   2. An-Noor     ..... 64 آیات
///   3. Al-Falaq    ..... 5  آیات
///   4. Quraysh     ..... 4  آیات
///   5. Al-Kawthar  ..... 3  آیات
///   6. Al-Mulk     ..... 30 آیات
///   7. Ar-Rahman   ..... 78 آیات
///   8. Al-Ikhlas   ..... 4  آیات
class SurahDetailScreen extends StatelessWidget {
  final String surahName;
  final String surahNumber;
  final String verses;

  const SurahDetailScreen({
    super.key,
    required this.surahName,
    required this.surahNumber,
    required this.verses,
  });

  /// Jo surahein app ke andar likhi hui nahi, wo Quran API se aati hain.
  /// Key surah ka naam, value Quran mein uska number.
  ///
  /// Al-Kahf ki 110 aayaat yahan hardcode nahi ki gayin — Quran ka matn
  /// mustanad source se aana chahiye, aur ek dafa aa kar phone par
  /// mehfooz ho jata hai.
  static const Map<String, int> _remoteSurahs = {
    'Al-Kahf': 18,
  };

  @override
  Widget build(BuildContext context) {
    final local = _getSurahVerses(surahName);
    if (local.isNotEmpty) {
      // سورۃ الفاتحہ میں بسم اللہ خود پہلی آیت ہے، اس لیے اوپر الگ سے نہیں دکھائیں گے
      return _buildScaffold(
        context,
        local,
        showBismillahHeader: surahName != 'Al-Fatihah',
      );
    }

    final remoteNumber = _remoteSurahs[surahName];
    if (remoteNumber == null) {
      return _buildScaffold(context, const [], showBismillahHeader: false);
    }

    return FutureBuilder<List<Map<String, String>>>(
      future: QuranApiService().getSurah(remoteNumber),
      builder: (context, snapshot) {
        if (snapshot.connectionState == ConnectionState.waiting) {
          return _buildLoading(context);
        }
        if (snapshot.hasError) {
          return _buildLoadError(context, '${snapshot.error}');
        }
        // API se aane wali pehli aayat mein Bismillah pehle se shamil
        // hota hai, is liye upar dobara nahi dikhate.
        return _buildScaffold(
          context,
          snapshot.data ?? const [],
          showBismillahHeader: false,
        );
      },
    );
  }

  Widget _buildLoading(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text('سورة ${_arabicName(surahName)}'),
        backgroundColor: Colors.green,
        foregroundColor: Colors.white,
        centerTitle: true,
      ),
      body: const Center(
        child: Column(
          mainAxisAlignment: MainAxisAlignment.center,
          children: [
            CircularProgressIndicator(color: Colors.green),
            SizedBox(height: 16),
            Text('Quran ka matn download ho raha hai...'),
            SizedBox(height: 4),
            Text(
              'Ek dafa ke baad offline bhi khulega',
              style: TextStyle(fontSize: 12, color: Colors.grey),
            ),
          ],
        ),
      ),
    );
  }

  Widget _buildLoadError(BuildContext context, String message) {
    return Scaffold(
      appBar: AppBar(
        title: Text('سورة ${_arabicName(surahName)}'),
        backgroundColor: Colors.green,
        foregroundColor: Colors.white,
        centerTitle: true,
      ),
      body: Center(
        child: Padding(
          padding: const EdgeInsets.all(24),
          child: Column(
            mainAxisAlignment: MainAxisAlignment.center,
            children: [
              const Icon(Icons.cloud_off, size: 56, color: Colors.grey),
              const SizedBox(height: 16),
              Text(
                message.replaceFirst('Exception: ', ''),
                textAlign: TextAlign.center,
                style: const TextStyle(color: Colors.black87),
              ),
              const SizedBox(height: 20),
              ElevatedButton.icon(
                onPressed: () => Navigator.pushReplacement(
                  context,
                  MaterialPageRoute(
                    builder: (_) => SurahDetailScreen(
                      surahName: surahName,
                      surahNumber: surahNumber,
                      verses: verses,
                    ),
                  ),
                ),
                icon: const Icon(Icons.refresh),
                label: const Text('Dobara koshish'),
                style: ElevatedButton.styleFrom(
                  backgroundColor: Colors.green,
                  foregroundColor: Colors.white,
                ),
              ),
            ],
          ),
        ),
      ),
    );
  }

